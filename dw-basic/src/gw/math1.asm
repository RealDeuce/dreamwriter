;
TAN:
DOL_TAN:	PUSH	word [DOL_FACM1] ;SAVE ARG
	PUSH	word [DOL_FACLO]
	CALL	DOL_SIN ;CALCULATE SINE
	POP	DX ;RECALL ARGUMENT
	POP	BX
	PUSH	word [DOL_FACLO] ;SAVE SIN(X)
	PUSH	word [DOL_FACM1]
	CALL	DOL_MOVFR ;MOVE ORIGINAL ARG TO FAC
	CALL	DOL_COS ;CALCULATE COSINE
	POP	BX ;RECALL SIN(X)
	POP	DX
	JMP	DOL_FDIVS ;GO DIVIDE TO EFFECT TANGENT
ATN:
DOL_ATAN: ;(FAC)=ARCTANGENT(FAC)
	MOV	AX,word [DOL_FAC-0o1] ;WANT ONLY POSITIVE X
	OR	AL,AL
	JNS	ATN10
	MOV	DI,DOL_NEG ;TAKE ADVANTAGE OF IDENTITY
	PUSH	DI ;ATAN(X)=-ATAN(-X)
	AND	AL,0o177 ;CLEAR SIGN
	MOV	byte [DOL_FAC-0o1],AL
ATN10:	CMP	AH,0o201 ;SEE IF X .GT. TAN(PI/4)
	JB	ATN20 ;IF NOT PROCEED
	MOV	DI,ATN100 ;WILL WANT TO FORM
	PUSH	DI ;PI/2-(FAC) AT THE END
	XOR	DX,DX ;WILL SET (BXDX)=1.0
	MOV	BX,0o100400
	CALL	DOL_FDIVS ;THIS PUTS 1/X IN FAC
ATN20:	MOV	DX,0o30242 ;FETCH TAN(PI/12)
	MOV	BX,0o77411
	CALL	DOL_FCOMP ;SEE IF LARGER
	JS	ATN30 ;IF NOT PROCEED
	MOV	DI,ATN200 ;WILL WANT (FAC)=(FAC)+PI/6
	PUSH	DI ;AT THE END
	PUSH	word [DOL_FACLO] ;SAVE X
	PUSH	word [DOL_FACM1]
	MOV	DX,0o131727 ;FETCH SQR(3)
	MOV	BX,0o100535
	CALL	DOL_FADDS ;(FAC)=X+SQR(3)
	POP	BX
	POP	DX ;FETCH X BACK
	PUSH	word [DOL_FACLO] ;SAVE X+SQR(3)
	PUSH	word [DOL_FACM1]
	CALL	DOL_MOVFR ;X TO FAC
	MOV	BX,DOL_ATNC1
	CALL	DOL_POLY ;FORM X*SQR(3)-1
	POP	BX
	POP	DX ;RECALL X+SQR(3)
	PUSH	word [DOL_FACLO] ;PUSH X*SQR(3)-1 ON STACK
	PUSH	word [DOL_FACM1]
	CALL	DOL_MOVFR ;X+SQR(3) TO FAC
	POP	BX
	POP	DX ;RECALL X*SQR(3)-1
	CALL	DOL_FDIVS ;FORM (X+SQR(3)-1)/(X+SQR(3))
ATN30:	MOV	BX,DOL_ATNC2 ;PREPARE FOR HART 4940
	JMP	DOL_POLYX
ATN100: MOV	DX,0o7733 ;FETCH PI/2
	MOV	BX,0o100511
	JMP	DOL_FSUBS ;(FAC)=PI/2-(FAC)
ATN200: MOV	DX,0o5222 ;FETCH PI/6
	MOV	BX,0o100006
	JMP	DOL_FADDS ;ADD PI/6 TO FAC
; SUBTTL	 $FINE	 ROUTINE TO ADJUST INPUT NUMBER FOR EXPONENT
;****************************************************************
;
;       $FINE   THIS ROUTINE MODIFIES THE CURRENT FAC WHICH HAS
;               THE INPUT SIGNIFICANT DIGITS SO THAT THE EXPONENT
;               IS REFLECTED IN THE NUMBER. FOR EXAMPLE, IF THE
;               NUMBER INPUT IS 1.9876E-17 THEN THE FAC CURRENTLY
;               HAS THE NUMBER 19876. IT MUST BE MULTIPLIED BY
;               10^-21 TO CORRECTLY REFLECT THE INPUT NUMBER.
;               IT IS THE JOB OF THIS ROUTINE TO DETERMINE THE
;               CORRECT MULTIPLIER AND PERFORM THE MULTIPLICATION
;       CALLING SEQUENCE        CALL    $FINE
;               WITH (SI) CONTAINING 0 IF POSITIVE EXPONENT
;               ALL BITS SET IF NEGATIVE EXPONENT. (DX) CONTAINS
;               THE INPUT EXPONENT(FOR THE EXAMPLE ABOVE =17)
;               AND (DI) CONTAINS THE NUMBER PLACES TO THE RIGHT
;               OF THE DECIMAL POINT.
;
;*****************************************************************
DOL_FINE:	OR	SI,SI ;SEE IF DX SHOULD BE NEGATED
	JNS	FIN05 ;IF NOT PROCEED
	NEG	DX ;NEGATE
FIN05:	SUB	DX,DI ;SUBTRACT OUT DIGITS TO RIGHT OF DP.
	JO	FIN80 ;UNDERFLOW IF OVERFLOW FLAG SET
	JZ	FIN55 ;NUMBER COMPLETE AS IS
;***************************************************************
;HERE WE HAVE THE EXPONENT IN DX. WE HAVE MULTIPLIERS RANGING
;FROM (10^-38,10^38) TO USE IN DETERMINING THE CORRECT FAC. WE
;MAY NEED TO DO SEVERAL MULTIPLIES TO CORRECTLY FORM THE NUMBER.
;FOR EXAMPLE IF THE NUMBER INPUT WAS 1234567.E-40 DX WOULD
;HAVE -40. IF THIS WERE THE CASE WE NEED TO DO A MULTIPLY BY 10^-38
;THEN A MULTIPLY BY 10^-2 TO GET THE RIGHT NUMBER.
;  All calculations are done in double precision and then converted
;back to the original type.  Integers are converted to single precision.
;****************************************************************
MDPTEN:
	PUSH	BX ; Preserve text pointer
	CALL	DOL_GETYP ; Get the current type,
	PUSHF ; And save, so that we can convert back
	JNB	FIN20 ; If already D.P., no conversion necessary
	CALL	FRCDBL ; Force result to be double precision
FIN20:	OR	DX,DX ; Test sign of exponent
	JS	FIN30 ;IF NEGATIVE EXPONENT JUMP
;********************************************************************
;POSITIVE EXPONENT . IF GREATER THAN D^38 THEN WE HAVE OVERFLOW
; Unless the number is zero, in which case just return zero.
;********************************************************************
	TEST	byte [DOL_FAC],0o377 ;Is the number zero?
	JZ	FIN80 ;Yes, just return zero then.
	CMP	DX,39
	JB	FIN40 ;OK PROCEED
	POPF ; Get back type flags
	JNB	FIN25 ; Already D.P., nothing to convert
	CALL	DOL_CSD ; Convert double to single
FIN25:	POP	BX ; Restore text pointer
	JMP	DOL_OVFLS ;OVERFLOW
;
; Negative exponent.
; Might require two divisions since highest table entry is 10^38.
;
FIN30:	CMP	DX,-38 ;Will one pass be enough?
	JGE	FIN40 ;Yes.
	ADD	DX,38 ;No, will two divisions get it?
	CMP	DX,-38
	JL	FIN80 ;No, underflow - return zero.
	CALL	MDP10 ;Yes, do the first one
	MOV	DX,-38 ;Then divide by 10^38.
FIN40:	CALL	MDP10 ; Do the division
FIN45:	POPF ; Get back type flags
	JNB	FIN50 ; Already D.P., nothing to convert
	CALL	DOL_CSD ; Convert double to single
; At this point the number is restored to its original type, with the
; exception of integers being converted to single precision.
FIN50:	POP	BX ; Restore text pointer
FIN55:	RET
FIN80:	CALL	DOL_ZERO ;UNDERFLOW!
	JMP	FIN45 ; Restore proper type
;
; Multiply or divide by double precision power of ten.
; On entry DX contains the exponent.
; If the exponent is postive, multiply.
; If exponent is negaive, divide.
;
MDP10:
	OR	DX,DX ;Is the exponent negative?
	PUSHF ;Remember whether to multiply or
;divide.
	JNS	POSEXP ;Positive exponent.
	NEG	DX ;Negative exponent, make it positive.
POSEXP: MOV	CX,0o3 ;DX:=DX*8 to get offset into powers
	SHL	DX,CL ;of ten table.
	ADD	DX,DOL_DP00 ;DX:=pointer to power of ten.
	XCHG	BX,DX ;Move it to BX.
	CALL	DOL_MOVAC ;MOVE D.P. NO. TO ARG
	POPF ;Divide?
	JS	DBLDIV ;Yes.
	JMP	DOL_FMULD ;No, multiply and return to caller
DBLDIV: JMP	DDIVFA ;Double precision divide; FAC=FAC/ARG,
; Return to caller.
; SUBTTL	 $OVFLS  OVERFLOW CODE
;***********************************************************
;
;       $OVFLS  PLACES CORRECT INFINITY IN THE FAC AND PRINTS
;               OVERFLOW MESSAGE
;
;       $DIV0S  PLACES CORRECT INFINITY IN THE FAC AND PRINTS
;               DIVIDE-BY-ZERO MESSAGE
;
;***********************************************************
DOL_OVFLS: PUSH	BX
	CALL	OVFLS ;DO THE OVERFLOW CODE
	POP	BX ;RESTORE TEXT POINTER
	RET
OVFLS:	CALL	DOINF ;PUT IN APPROPRIATE INFINITY
	MOV	AX,OVERR ;Error trapping routine adr
	MOV	BX,DOL_OVMSG ;ADDRESS APPROPRIATE ERROR MESSAGE
	JMP	DV010 ;GO PRINT MESSAGE
DOL_DIV0S: PUSH	BX ;SAVE TEXT POINTER
	CALL	DIV0S ;DO THE DIVIDE OVERFLOW CODE
	POP	BX
	RET ;RETURN WITH TEXT POINTER SAVED
DIV0S:	CALL	DOINF ;PUT IN APPROPRIATE INFINITY
	MOV	AX,DV0ERR ;Error trapping routine adr
	MOV	BX,DOL_DIV0M ;AND ERROR MESSAGE
DV010:	CALL	TRAPER ;Trap error if error trapping enabled
	CMP	byte [DOL_FLGOV],0o1 ;IF 0,1 PRINT, IF 1 MAKE 2
	JS	DV015 ;PRINT IF 0
	JNZ	DV020 ;DON'T PRINT IF 2
	MOV	byte [DOL_FLGOV],0o2 ;MAKE 2 IF 1
DV015:	CALL	DOL_STPRN
	MOV	AL,0o15 ;CARRIAGE RETURN
	CALL	DOL_CATTY ;SEND IT
	MOV	AL,0o12 ;LINE FEED
	CALL	DOL_CATTY ;SEND IT
DV020:	RET
DOINF: ;PUT CORRECT INFINITY IN THE FAC
	CLD ;CLEAR THE DIRECTION FLAG "DF"
	OR	BH,BH ;SEE IF ZERO TO A NEG POWER
	MOV	SI,DOL_INFPD ;ASSUME POSITIVE
	JZ	INF10 ;POSITIVE INFINITY FOR ZERO^-X
	TEST	byte [DOL_FAC+0o1],0o200 ;NEGATIVE?
	JNS	INF10 ;IF NOT PROCEED
	MOV	SI,DOL_INFMD ;NEGATIVE INFINITY
INF10:	CALL	DOL_GETYP ;SET CODES ACCORDING TO TYPE
	JB	INF20
;***********************************************************
;IT'S DOUBLE PRECISION
;***********************************************************
	MOV	DI,DOL_DFACL ;RECEIPIENT
	MOV	CX,0o4 ;4 WORDS FOR DOUBLE PRECISION
	JMP	INF30
INF20: ;SINGLE PRECISION
	ADD	SI,0o4 ;SO WE POINT TO SINGLE PRECISION NO.
	MOV	DI,DOL_FACLO
	MOV	CX,0o2 ;2 WORDS FOR SINGLE
INF30: ;MUST FETCH FROM CODE SEGMENT
	cs movsw ;TO FAC
	LOOP	INF30
	RET
TRAPER: PUSH	AX ;save Error trapping routine adr
	MOV	AX,word [ONELIN]
	OR	AX,AX ;see if we are trapping errors
	JNZ	TRAPIT ;branch if errors are being trapped
	POP	AX ;discard Error trapping routine adr
TRAPIT: RET ;return to caller or Error trap routine
; SUBTTL	 $FOFMT  FLOATING FORMAT OF NUMBER IN THE FAC
;**************************************************************
;
;       $FOFMT  FORMAT THE NUMBER IN THE FAC. IF THE NUMBER CAN BE
;               AS ACCURATELY REPRESENTED IN FIXED FORMAT AS
;               SCIENTIFIC THEN USE FIXED OUTPUT.
;       CALLING SEQUENCE:       CALL    $FOFMT
;               WITH (BX) POINTING TO CURRENT OUTPUT POSITION
;               IN THE OUTPUT BUFFER $FBUFF AND CONDITION CODES
;               SET AS IF $GETYP WAS JUST CALLED
;
;*****************************************************************
DOL_FOFMT: PUSH	BX ;SAVE BUFFER POINTER
	MOV	AL,8 ;assume single precision - print 7 digits
	JB	FFM10 ;JUMP IF SINGLE PRECISION
	MOV	AL,17 ;DOUBLE PRECISION POSSIBLE DIGITS
FFM10:	MOV	CH,AL ;WILL SAVE A SECOND COPY FOR LATER
	MOV	CL,AL
	PUSH	CX ;SAVE FOR LATER
	PUSHF ;SAVE TYPE
	CALL	DOL_FOTNV ;BRACKET THE NUMBER SO THAT SIGNIFICANT
;DIGITS ARE IN THE INTEGER PART AND
;THE NECESSARY EXPONENT IS IN (AL)
	OR	AL,AL ;IF POSITIVE DON'T CALL SIGD
	JZ	FFM11
	JNS	FFM15
FFM11:	POPF ;RECALL TYPE FOR TEST TO SEE IF SIGD
;CALLED. IF S.P. AND (AL) SMALLER THAN
;-7 MUST CALL SIG, IF D.P. AND (AL)
;SMALLER THAN -16 THEN MUST CALL SIGD.
;IF (AL) POSITIVE SIGD WILL NOT BE
;CALLED. PURPOSE OF SIGD IS TO
;DETERMINE WHETHER WE CAN PRINT NO. IN
;FIXED FORMAT W/O LOSING SIGNIFICANT
;DIGITS.
	POP	CX ;RECALL POSIBLE SIGNIFICANT SIGITS
	PUSH	AX ;SAVE EXP.
	JPO	FFM16 ;SINGLE PREC.
	ADD	AL,16 ;THIS MUST MAKE POSITIVE TO NOT CALL
	POP	AX
	JNS	FFM18 ;POP AX AND DO FIXED OUTPUT
	JMP	FFM17 ;MUST CALL SIGD
FFM15:
	POPF ;RECALL TYPE FLAG
	POP	CX ;RECALL CX
	JMP	FFM20
FFM16:
	ADD	AL,0o7
	POP	AX
	JNS	FFM18
FFM17:
	PUSH	AX ;SAVE NECESSARY EXPONENT IN (AL)
	CALL	DOL_SIGD ;INCREMENT (CL) FOR EACH ZERO DIGIT
;BEGINNING FROM THE RIGHT
	POP	AX ;RECALL NECESSARY EXPONENT
	MOV	AH,AL ;WILL PERFORM FIRST TEST ON AH
	ADD	AH,CL ;IF SF=1 AFTER THIS THEN USE "E" FORMAT
	JLE	FFM20 ;JUMP IF TOO SMALL
	ADD	CH,AL
	JMP	FFM19
FFM18:	ADD	AL,CH
	INC	CH
	CMP	CH,AL
	MOV	CH,0o3 ;TO FLAG "E" FORMAT IF NECESSARY
	JB	FFM30
	MOV	CH,AL
FFM19:	INC	CH ;(CH)= NUMBER DIGITS+2
	MOV	AL,0o2 ;THIS WILL CAUSE ZF=1 IN LATER CALC
;AND WILL SIGNAL FIXED OUTPUT
	JMP	FFM30
FFM20:	ADD	AL,CH
	MOV	CH,0o3 ;SIGNALS "E" TYPE FORMAT
FFM30:	DEC	AL ;(AL) 2 TOO LARGE
	DEC	AL
	POP	BX ;RECALL BUFFER POINTER
	PUSH	AX ;SAVE EXPONENT
	PUSHF ;SAVE CONDITION CODES
	XOR	CL,CL ;(CL)=0  (NO COMMAS AFTER EACH 3 DIGITS
	CALL	DOL_FOTAN ;PUT IN DECIMAL POINT AND LEADING
;ZEROS AS NECESSARY
	MOV	byte [BX+0o0],"0" ;ZF=1 IF THIS "0" NECESSARY
	JNZ	FFM40
	INC	BX
FFM40:	CALL	DOL_FOTCV ;CONVERT THE FAC TO DECIMAL DIGITS
;AND PUT IN DECIMAL POINT AS NECESSARY
FFM50:	DEC	BX ;WILL NOW SEE IF THERE ARE TRAILING
	CMP	byte [BX+0o0],"0" ;ZEROS TO SUPPRESS. WE KNOW ZEROS WE
	JZ	FFM50 ;FIND HERE ARE TRAILING BECAUSE $FOTCV
	CMP	byte [BX+0o0],"." ;PUTS IN DECIMAL POINT
	JZ	FFM60 ;CAN WE DELETE THE DECIMAL POINT ALSO?
	INC	BX ;
FFM60:	POPF ;LET'S HAVE A LOOK AT THE POSSIBLE
;EXPONENT
	POP	AX
	JZ	FFM100 ;IF NO EXPONENT JUST CLEAN-UP AND RET
DOL_PUEXP: PUSHF ;SAVE SF( IF =1 NEGATIVE EXPONENT)
	PUSH	AX ;SAVE EXPONENT
	CALL	DOL_GETYP ;SET COND. CODES FOR TYPE NUMBER
	MOV	AH,"E" ;ASSUME SINGLE PRECISION
	JPO	FFM70 ;IF S.P. PROCEED
	MOV	AH,"D" ;IT'S DOUBLE PRECISION
FFM70:	MOV	byte [BX+0o0],AH ;PUT IN EXPONENT DESIGNATOR
	INC	BX ;POINT TO NEXT BUFFER POSITION
	POP	AX ;RECALL EXPONENT
	POPF ;NOW TO SEE IF POSITIVE OR NEGATIVE
	MOV	byte [BX+0o0],"+" ;ASSUME POSITIVE EXPONENT
	JNS	FFM80 ;AND JUMP IF SO
	MOV	byte [BX+0o0],"-"
	NEG	AL ;MUST MAKE EXPONENT POSITIVE
FFM80:	MOV	AH,"0"-0o1 ;WILL BUILD DIGIT IN (AL)
FFM90:	INC	AH ;INCREMENT TO NEXT DIGIT
	SUB	AL,10 ;
	JNB	FFM90
	ADD	AL,"0"+10 ;ADD TO DETERMINE SECOND DIGIT
	INC	BX ;POINT TO NEXT BUFFER POSITION
	XCHG	AL,AH ;PREPARE FOR WORD STORE
	MOV	word [BX+0o0],AX ;STORE 2 DIGITS OF EXPONENT
	INC	BX ;INCREMENT TO NEXT BUFFER POSITION
	INC	BX
FFM100: MOV	byte [BX+0o0],0o0 ;SIGNAL END OF BUFFER DATA
	XCHG	BX,CX ;END-OF-BUFFER PTR. IN (CX)
	MOV	BX,DOL_FBUFF+0o1 ;START IN (BX)
	RET
; SUBTTL	 UTILS	   UTILITY ROUTINES
;string printer must fetch from code segment
STOULP: CALL	OUTDO ;send char
	CMP	AL,13 ;carriage return?
	JNZ	STROUT ;no
	CALL	CRFIN ;force carriage back to left
STROUT: ;fetch from code segment
	MOV	AL,byte [CS:BX+0o0] ;get char
	INC	BX ;point at next one
	OR	AL,AL ;end of string?
	JNZ	STOULP ;no print char until done
	RET
DOL_DZERO: ;DOUBLE PRECISION ZERO
	MOV	DI,DOL_DFACL
	MOV	CX,0o4
	MOV	AX,0o0
	CLD
 REP	STOSW
	RET
ZERO:
DOL_ZERO: ;ZERO THE FAC
	MOV	AX,0o0
	MOV	word [DOL_FACLO],AX ;ZERO LOWER 2 BYTES
	MOV	word [DOL_FAC-0o1],AX ;ZERO UPPER TWO BYTES
	RET
SIGN:
DOL_SIGNS: ;DETERMINE SIGN OF FAC
;ZF=1 IF ($FAC)=0, SF=1 IF ($FAC) .LT.0, NEITHER OF
;THESE FLAGS SET IF ($FAC).GT.0
	CALL	DOL_GETYP ;IF NOT INTEGER CAN LOOK AT FAC:FAC-1
	JNE	SIS01
	JMP	TMERR ;Strings illegal 9-Mar-82/ngt
SIS01:
	JNS	SIS05 ;NOT INTEGER PROCEED
	MOV	AX,word [DOL_FACLO] ;FETCH INTEGER
	OR	AX,AX ;DETERMINE SIGN
	JZ	SIS10
	MOV	AL,0o1
	JNS	SIS10
	NEG	AL
	RET
SIS05:
	MOV	AL,byte [DOL_FAC] ;FIRST CHECK FOR ZERO
	OR	AL,AL
	JZ	SIS10 ;IF ZERO JUST RETURN
	MOV	AL,byte [DOL_FAC-0o1] ;FETCH SIGN BYTE
SIGNAL: OR	AL,AL ;SIGNSET NOW
	JZ	SIS07 ;MUST MAKE AL=1 AND ZF=0
	MOV	AL,0o1
	JNS	SIS10
	NEG	AL
	RET
SIS07:	OR	AL,0o1 ;KNOW POSITIVE NON-ZERO
SIS10:	RET
;
; Set cond. codes according to type value.
;   S, C = Integer
;   Z, C = String
;      C = Single Precision
;   None = Double Precision
;
DOL_GETYP:
	MOV	AL,byte [DOL_VALTP] ;FETCH TYPE VARIABLE
	CMP	AL,0o10 ;CF=1 EXCEPT FOR DOUBLE PREC.
	DEC	AL ;WILL SUBTRACT 3 WITH DECBREMENTS
	DEC	AL
	DEC	AL
	RET ;ZF=1 IF STRING,SF=1 IF INTEGER
;PO=1 IF SINGLE PREC
DOL_VADDH: ;ADD .5 ACCORDING TO TYPE
	CALL	DOL_GETYP ;SET CODES ACCORDING TO TYPE
	JB	DOL_FADDH
DOL_DADDH: ;DOUBLE PRECISION ADD .5
	PUSH	BX
	MOV	BX,DOL_DHALF
	CALL	DOL_MOVAC ;MOVE TO ARG
	CALL	DOL_FADDD ;ADD TO FAC
	POP	BX
	RET
DOL_FADDH: ;SINGLE PRECISION ADD .5
	XOR	DX,DX ;WILL SET (BXDX)=.5
	MOV	BX,0o100000
	CALL	DOL_FADDS ;ADD .5 TO FAC
	RET
DOL_DIV10: ;DIVIDE FAC BY 10
	CALL	DOL_GETYP
	MOV	BX,DOL_DPM01 ;ADDRESS .1
	JB	ML10
	JMP	ML05 ;MULTIPLY
DOL_MUL10: ;MULTIPLY THE FAC BY 10
	CALL	DOL_GETYP ;SEE IF SINGLE OR DOUBLE PREC
	MOV	BX,DOL_DP01 ;ADDRESS OF DOUBLE PREC 10.
	JB	ML10 ;JUMP IF SINGLE
ML05:	CALL	DOL_MOVAC ;MOVE 10. TO ARG
	CALL	DOL_FMULD ;MULTIPLY
	RET
ML10: ;MULTIPLY SINGLE PREC. FAC BY NO. POINTED TO BY BX
DOL_MLSP:
	PUSH	word [DOL_FACM1] ;PUSH FAC ON THE STACK
	PUSH	word [DOL_FACLO]
	MOV	byte [DOL_VALTP],0o10 ;SET UP D.P.
	CALL	DOL_MOVFC ;MOVE DOUBLE PREC. 10 TO FAC
	CALL	DOL_CSD ;CONVERT TO SINGLE PRECISION
	POP	DX ;GET LOW MANTISSA BITS
	POP	BX ;EXP SIGN AND HIGH MATISSA BITS
	CALL	DOL_FMULS ;MULTIPLY
	RET
DOL_RDL:	MOV	CX,0o4 ;WILL SHIFT 4 WORDS LEFT
RDL120: RCL	word [BX+0o0],0o1 ;SHIFT  LEFT 1 BIT SHIFTING IN CF
	INC	BX
	INC	BX
	LOOP	RDL120
	RET
DOL_SHDR:	MOV	CX,0o4 ;DO DOUBLE PRECISION RIGHT SHIFT
DOL_SHRM: ;SHIFT NO. POINTED TO BY (BX) , (CX) WDS RT.
	RCR	word [BX+0o0],0o1 ;SHIFT 1 WD. RT. THRU CF
	DEC	BX
	DEC	BX ;TO NEXT WD.
	LOOP	DOL_SHRM ;DO THIS (CX) TIMES
	RET
SHST:	OR	byte [BX+0o2],0o40 ;"OR" IN ST BIT
	LOOP	DOL_SHRA
	RET
DOL_SHRA: ;SHIFT $ARG RIGHT (CX) BITS
	MOV	BX,DOL_ARG-0o2
	CMP	CL,0o10 ;CAN I DO A BYTE MOVE
	JB	SHRA30 ;IF NOT PROCEED AS NORMAL
;*************************************************************
;FOR SPEED PURPOSES WE WILL DO A BYTE MOVE TO THE RIGHT
;*************************************************************
	PUSH	CX ;SAVE BITS TO SHIFT
	MOV	CX,0o7 ;7 BYTE MOVE
	MOV	BX,DOL_ARGLO-0o1
	MOV	AH,byte [BX+0o0] ;FETCH OVERFLOW BYTE
SHRA11: MOV	AL,byte [BX+0o1]
	MOV	byte [BX+0o0],AL
	INC	BX
	LOOP	SHRA11
	XOR	AL,AL
	MOV	byte [BX+0o0],AL
	POP	CX ;RECALL BIT COUNT
	SUB	CL,0o10
	AND	AH,0o40 ;WILL NEED TO RE-ESTABLISH ST
	JZ	DOL_SHRA ;NO-ST JUST PROCEED
	OR	byte [DOL_ARGLO-0o1],AH
	JMP	DOL_SHRA
SHRA30:
	OR	CL,CL
	JZ	SHRA40 ;JUMP IF DONE
	PUSH	CX ;SAVE NO. BITS TO SHIFT
	CLC ;DON'T WANT THE CARRY SHIFTED IN
	CALL	DOL_SHDR
	POP	CX
	TEST	byte [BX+0o2],0o20 ;SEE IF SHIFTED THRU "ST"
	JNZ	SHST ;MUST "OR" ST BIT IN IF NON-ZERO
	LOOP	DOL_SHRA
SHRA40: RET
DOL_XCGAF: MOV	SI,DOL_DFACL ;WILL EXCHANGE FAC AND ARG (D.P.)
	MOV	DI,DOL_ARGLO
	CLD ;SO MOVW WILL INCREMENT INDICES
	MOV	CX,0o4 ;WILL MOVE 4 WORDS (8 BYTES)
XCG10:	MOV	AX,word [DI+0o0] ;FETCH DESTINATION WORD
	MOVSW ;MOVE FAC TO ARG & INCREMENT INDICES
	MOV	word [SI-0o2],AX ;ARG TO FAC
	LOOP	XCG10 ;CONTINUE
	RET
;*********************************************************************
;       SPECIAL MOVE ROUTINES FOR HANDLING CONSTANTS FROM THE CODE
;       SEGMENT
;*********************************************************************
DOL_MOVBS: ;THIS ROUTINE IS USED TO MOVE A SINGLE PRECISION NO. FROM THE
;CODE SEGMENT TO $DBUFF. THE NO. IS POINTED TO BY (BX)
	MOV	DI,DOL_DBUFF+0o4
	MOV	CX,0o2
	JMP	MBF10
DOL_MOVBF: ;THIS ROUTINE IS USED TO MOVE A DOUBLE PRECISION NO. FROM THE
;CODE SEGMENT TO $DBUFF. THE NO. IS POINTED TO BY (BX)
	MOV	DI,DOL_DBUFF
MBF05:	MOV	CX,0o4
MBF10:	CLD
	MOV	SI,BX ;SO WE CAN USE A LODW
MBF20:
	cs lodsw ;FETCH FROM CS
	STOSW ;STORE IN DBUFF
	LOOP	MBF20 ;CONTINUE WITH MOVE
	MOV	BX,DI ;UPDATE (BX)
	SUB	BX,0o2 ;GET POINTER CORRECT
	RET
DOL_MOVAC: ;ROUTINE TO MOVE A DOUBLE PRECISION NO. POINTED TO BY (BX)
;FROM THE CODE SEGMENT TO ARG
	MOV	DI,DOL_ARGLO
	JMP	MBF05
DOL_MOVFC: ;ROUTINE USED TO MOVE A DOUBLE PRECISION NO. FROM THE CODE
;SEGMENT TO THE FAC. NO. IS POINTED TO BY (BX)
	MOV	DI,DOL_DFACL
	JMP	MBF05
MOVAM: ;MOVE NO. POINTED TO BY BX TO ARG
	MOV	DI,DOL_ARGLO ;LOW ADDRESS OF ARG
	MOV	CX,0o4 ;MOVE DOUBLE PREC NO. POINTED TO
;BY (BX) TO DOUBLE PREC NO. POINTED TO
;BY (DI)
MOVEM: ;MOVE NO. POINTED TO BY (BX) TO NO. POINTED TO BY (DI)
;FOR (CX) WORDS
	XCHG	BX,SI ;SO MOVW CAN BE USED
	CLD ;SO MOVW WILL INC
;DO MOVE (CX) TIMES
 REP	MOVSW ;MOVE "FROM" TO "TO"
	XCHG	BX,SI ;GET REGISTERS STRAIGHT
	RET
DOL_MOVAF: ;MOVE THE $FAC TO $ARG
	PUSH	CX ;SAVE CX,BX,DI
	PUSH	BX
	PUSH	DI
	MOV	BX,DOL_DFACL ;"FROM" ADDRESS
	MOV	DI,DOL_ARGLO ;"TO" ADDRESS
MAF05:	MOV	CX,0o4 ;4 16-BIT QUANTITIES TO MOVE
	CALL	MOVEM ;DO THE MOVE
	POP	DI
	POP	BX
	POP	CX ;REGISTERS RESTORED
	RET
DOL_MOVFA: ;MOVE THE $ARG TO THE FAC
	PUSH	CX
	PUSH	BX
	PUSH	DI ;SAVE REGISTERS
	MOV	BX,DOL_ARGLO ;"FROM" ADDRESS
	MOV	DI,DOL_DFACL ;"TO" ADDRESS
	JMP	MAF05 ;GO MOVE
