;SINGLE PRECISION MOVE ROUTINES
;***************************************************************
DOL_MOVFR: ;MOVE (BXDX) TO FAC
	MOV	word [DOL_FACLO],DX
	MOV	word [DOL_FAC-0o1],BX
	RET
