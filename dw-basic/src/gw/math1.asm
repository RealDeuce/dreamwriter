	RET ;(BX) POINTING HERE
FX10:	CALL	DOL_CHRGT ;GET NEXT CHARACTER
	JB	FX20 ;IF DIGIT PROCESS AS EXPONENT
	RET ;OTHERWISE RETURN
FX20:	CMP	DX,3276 ;OVERFLOW IF THIS DOESN'T GET CF=1
