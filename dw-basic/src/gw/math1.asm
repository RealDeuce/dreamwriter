; SUBTTL	 $FPWR/$SQR	 INVOLUTION/SQUARE RT. OF SINGLE PRECISION NOS.
;***********************************************************
;
;       $FPWR   CALCULATES X^Y BY X^Y=EXP(Y*LOG(X))
;
;       CALLING SEQUENCE:       CALL    $FPWR
;               WITH Y IN THE $FAC, X IN (BXDX)
;       $SQR    ENTRY POINT TO PROVIDE SQUARE ROOT FUNCTION
;       CALLING SEQUENCE:       CALL    $SQR
;               WITH ARGUMENT IN $FAC
;
;************************************************************
;SQUARE ROOT FUNCTION (FAC)=SQR(FAC)
SQR:
DOL_SQR:
	MOV	DX,word [DOL_FAC-0o2]
	OR	DH,DH ;Test sign bit
	JS	NEGNUM
	MOV	AL,byte [DOL_FAC] ;Get exponent
	OR	AL,AL
	JZ	DONE ;SQR(0)=0
	MOV	BH,byte [DOL_FAC-0o3]
	MOV	BL,0o0
	OR	DH,128 ;Set implied bit
	SHR	AL,0o1 ;Divide exponent by two
	JNB	EVENEX ;
	SHR	DX,0o1 ;HALF MANTISSA IF EXP ODD
	RCR	BX,0o1
	STC ;RESTORE CARRY FOR ROUND UP
EVENEX:
	ADC	AL,0o100 ;ADD BACK 1/2 OF BIAS
	MOV	byte [DOL_FAC],AL ;SAVE FINAL EXPONENT
	MOV	CX,25 ;24 BITS PLUS 1 FOR ROUNDING
	XOR	BP,BP ;CLEAR SOME REGISTERS
	MOV	SI,BP
	MOV	DI,BP
	MOV	AX,BP
RTLP:
	SHL	BX,0o1 ;64 BIT LEFT SHIFT OF INPUT
	RCL	DX,0o1
	RCL	DI,0o1
	RCL	BP,0o1
	SHL	BX,0o1 ;SHIFT IT TWICE
	RCL	DX,0o1
	RCL	DI,0o1
	RCL	BP,0o1
	STC ;ROTATE IN TEST BIT
	RCL	SI,0o1 ;32-BIT SHIFT OF PARTIAL RESULT
	RCL	AX,0o1
	SUB	DI,SI ;TRY TEST BIT
	SBB	BP,AX
	JNB	ROOTBT ;JUMP OUT IF IT FIT
	ADD	DI,SI ;RESTORE IF IT DIDN'T
	ADC	BP,AX
	DEC	SI
	LOOP	RTLP
	JMP	FPWRND
ROOTBT:
	INC	SI ;HERE IF TEST BIT FIT
	LOOP	RTLP ;SET REAL RESULT BIT AND CONTINUE
FPWRND:
	SHR	AX,0o1 ;HALF TO A 25-BIT RESULT
	RCR	SI,0o1
	SHR	AX,0o1 ;TO A 24-BIT RESULT
	RCR	SI,0o1
	ADC	SI,0o0 ;ROUND IF A 1 SHIFTED OUT
