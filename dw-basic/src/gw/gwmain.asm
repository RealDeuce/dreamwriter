	OR	DX,DX ;SET CC'S ON LINK FIELD
	XCHG	BX,DX ;SEE IF NEXT LINK ZERO
	POP	DX ;GET BACK ACCUM LINE #
	JZ	RESSD1 ;ZERO, DONE
