	MOV	AL,PLUSTK ;PLUS SIGN IS OK AND AVOIDS CONSTANT
CKSNGQ: CMP	AL,SNGQTK ;SINGLE QUOATATION MARK?
	JZ	??L029
	JMP	NTSNGT
