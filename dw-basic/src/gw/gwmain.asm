	MOV AL, byte [CHNFLG] ;ONLY CHANGET FRETOP IF NOT CHAINING
	OR	AL,AL
	JNZ	LEVFRE ;LEAVE FRETOP ALONE
	MOV BX, [MEMSIZ] ;DELETE ALL STRINGS
	MOV [FRETOP], BX ;SO REASON DOESNT USE THEM
