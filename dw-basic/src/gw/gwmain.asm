	POP	CX ;RESTORE CHAR COUNT
	POP	DX ;RESTORE DEPOSIT POINTER
	PUSH	BX ;SAVE TEXT POINTER
	MOV AL, byte [VALTYP] ;GET VALUE TYPE
	CMP	AL,2 ;INTEGER?
	JNZ	NTINTG ;NO
	MOV BX, [FACLO] ;GET IT
	MOV	AL,BH ;GET HIGH PART
	OR	AL,AL ;IS IT ZERO?
	MOV	AL,2 ;RESTORE INT VALTYP
	JNZ	NTINTG ;THEN ISNT SINGLE BYTE INT
