	AND	AL,127 ;GET RID OF HIGH BIT
	JNZ	??L023
	JMP	NOTRES ;IF=0 THEN END OF THIS CHARS RESLT
??L023:
	INC	BX ;BUMP SOURCE POINTER
	CMP	AL,CL ;COMPARE TO CHAR FROM SOURCE LINE
	JNZ	LOPSKP ;IF NO MATCH, SEARCH FOR NEXT RESWRD
