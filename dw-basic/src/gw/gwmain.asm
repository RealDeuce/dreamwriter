	PUSH	BX ;SAVE LINK FIELD
	MOV	BX,65529 ;TEST FOR TOO LARGE LINE
	CMP	BX,DX ;COMPARE TO CURRENT #
	POP	BX ;RESTORE LINK FIELD
	JAE	??L091
	JMP	FCERR ;UH OH, HIS INC WAS TOO LARGE.
??L091:
