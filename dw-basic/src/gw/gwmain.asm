	CMP	AL,TOK_FN ;FUNCTION?
	JZ	ISRESW ;THEN NO SPACE NEED AFTERWARD
	CMP	AL,TOK_USR ;OR USR DEFINITION?
	JZ	ISRESW
	CALL	MAKUPL ;GET NEXT CHAR IN LINE (MC 6/22/80)
	CMP	AL,"." ;IS IT A DOT
	JZ	ISVARS ;YES
	CALL	TSTANM ;IS IT A LETTER IMMEDIATELY FOLLOWING RESWRD
ISVARS: MOV	AL,0 ;SET DONUM TO -1
	JNAE	??L025
	JMP	NOTRES ;IF ALPHA, CANT BE RESERVED WORD
??L025:
ISRESW:
	POP	AX ;GET RID OF SAVED [H,L]
db 0o213
db 0o362
db 0o56
db 0o254 ;FETCH FROM CODE SEGMENT
	OR	AL,AL ;SET CC'S
	JNS	??L026
	JMP	NOTFNT ;IF MINUS, WASNT FUNCTION TOKEN
??L026:
	POP	CX ;GET CHAR COUNT OFF STACK
	POP	DX ;GET DEPOSIT POINTER OFF STACK
	OR	AL,0o200 ;MAKE HIGH ORDER BIT ONE
	PUSH	AX ;SAVE FN CHAR
	MOV	AL,0o377 ;GET BYTE WHICH PRECEEDS FNS
