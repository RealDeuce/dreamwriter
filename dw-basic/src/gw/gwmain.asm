	XCHG	AL,AH
	PUSH	AX
	XCHG	AL,AH ;PUT GOSUB TOKEN ON THE STACK
	PUSH	CX ;SAVE NEWSTT ON STACK
	JMP	GOTO2 ;HAVE NOW GRAB LINE # PROPERLY
